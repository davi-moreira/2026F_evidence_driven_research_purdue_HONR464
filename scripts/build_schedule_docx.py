"""Build the standalone HONR 46400 course-schedule .docx.

A companion to scripts/build_syllabus_docx.py and a sibling of QM 47400's
scripts/build_schedule_docx.py, whose design this reproduces: landscape letter,
Purdue palette, a black header band in Old Gold, alternating week bands, a
heavier rule at each week boundary, shaded no-class rows, accent shading for the
marquee events, a repeating header row, a Final Project milestone table, and a
page footer.

QM474's version parses its own schedule.qmd, whose table is five columns. HONR's
schedule page is eight columns and is regenerated by a different script, so this
build takes its rows from the same place the syllabus .docx does - the shared
helpers in build_syllabus_docx - which keeps the two documents in agreement and
keeps both anchored to planning/MEETING_SCHEDULE.csv.

Run:  .venv/bin/python scripts/build_schedule_docx.py
"""
